// Writes website/src/version.js from the library's package.json, so the site
// cannot claim a version the repo does not ship.
//
// A generated module rather than a lookup in afw.config.js: the navbar badge
// also renders in the browser, where there is no package.json to read. Runs as
// part of every site build (`tsr build:website`, scripts/build-site.sh); run it
// alone with `tsr site:version`.
import { write } from "runtime:fs";
import pkg from "../packages/syntax-highlighter/package.json" with { type: "json" };

const version = pkg.version;
if (!/^\d+\.\d+\.\d+/.test(version ?? ""))
  throw new Error(`no version in package.json: ${version}`);

const out = new URL("../website/src/version.js", import.meta.url);
await write(
  out,
  `// AUTO-GENERATED by scripts/site-version.mjs from packages/syntax-highlighter/package.json.
// Do not edit by hand — regenerate with: tsr site:version
export const version = ${JSON.stringify(version)};
`,
);

console.log(`@opentf/syntax-highlighter ${version} → website/src/version.js`);
